'''

➕ Adição print(5 + 3)  # 8

➖ Subtração
print(5 - 3)  # 2

✖️ Multiplicação
print(5 * 3)  # 15

➗ Divisão (resultado com decimal)
print(5 / 2)  # 2.5

🔽 Divisão inteira (sem decimal)
print(5 // 2)  # 2

🔁 Resto da divisão (módulo %)
print(5 % 2)  # 1

🔼 Potência
print(2 ** 3)  # 8

'''  

'''
Operadores de Comparação

Sempre retornam True ou False

x = 10

Igual
x == 10  # True

Diferente
x != 5  # True

Maior que
x > 5  # True

Menor que
x < 20  # True

Maior ou igual
x >= 10  # True

Menor ou igual
x <= 9  # False 
'''

'''
Operadores Lógicos

Usados para combinar condições

AND (e)

👉 Precisa que tudo seja verdadeiro

x = 10

print(x > 5 and x < 20)  # True
OR (ou)

👉 Apenas uma condição precisa ser verdadeira

print(x > 5 or x > 20)  # True
NOT (negação)

👉 Inverte o resultado

print(not True)  # False
'''

'''
4. Operadores de Atribuição

Servem para guardar valores

Atribuição simples
x = 10

Soma e atribui
x += 5  # x = x + 5

Subtrai e atribui
x -= 2

Multiplica e atribui
x *= 3

Divide e atribui
x /= 2
'''

'''
Operadores de Identidade

Verificam se são o mesmo objeto na memória

is
a = [1, 2]
b = a

print(a is b)  # True
is not
print(a is not b)  # False

👉 Avançado: diferente de ==
'''

'''
Operadores de Associação (Membership)

Verificam se algo existe dentro de outro

in
lista = [1, 2, 3]

print(2 in lista)  # True
not in
print(5 not in lista)  # True
'''

#⚠️ Dicas importantes

# = não é comparação, é atribuição

# == é comparação

# % = resto da divisão

# // = divisão sem decimal